"""Contrato de armazenamento (o pipeline e a busca só conhecem esta interface)."""

from __future__ import annotations

from typing import Protocol

from .entities import SearchHit


class VectorStore(Protocol):
    async def ensure_schema(self) -> None: ...

    # fontes
    async def upsert_source(self, name: str, kind: str, root_path: str | None) -> int: ...
    async def find_source(self, name: str | None = None, root_path: str | None = None) -> dict | None: ...
    async def list_sources(self) -> list[dict]: ...
    async def delete_source(self, source_id: int) -> None: ...

    # arquivos e chunks
    async def file_hashes(self, source_id: int) -> dict[str, str]: ...
    async def delete_files(self, source_id: int, paths: list[str]) -> None: ...
    async def get_summaries(self, hashes: list[str], kind: str | None = None) -> dict[str, tuple[str, str]]: ...
    async def paths_with_other_summaries(self, source_id: int, kind: str) -> list[str]: ...
    async def summary_counts(self, source_id: int) -> dict[str, int]: ...
    async def replace_file_chunks(self, source_id: int, path: str, sha1: str, language: str, rows: list[dict]) -> None: ...
    async def outline(self, source_id: int) -> list[dict]: ...

    # busca
    async def search_vector(self, source_ids: list[int], embedding: list[float], limit: int, path_prefix: str | None) -> list[SearchHit]: ...
    async def search_text(self, source_ids: list[int], tokens: list[str], limit: int, path_prefix: str | None) -> list[SearchHit]: ...
    async def search_symbol(self, source_ids: list[int], tokens: list[str], limit: int, path_prefix: str | None) -> list[SearchHit]: ...

    # jobs
    async def create_job(self, source_id: int) -> int: ...
    async def update_job(self, job_id: int, **fields) -> None: ...
    async def get_job(self, job_id: int) -> dict | None: ...
    async def latest_job(self, source_id: int) -> dict | None: ...
    async def fail_stale_jobs(self) -> int: ...

    # vínculos: projeto (caminho do workspace) → fontes extras que o agente também consulta
    async def set_workspace_links(self, root: str, source_ids: list[int]) -> None: ...
    async def get_workspace_links(self, root: str) -> list[int]: ...
